#!/bin/bash
# Executed by ARM bash inside chroot; services must not start in the builder.
set -euo pipefail
export DEBIAN_FRONTEND=noninteractive LC_ALL=C
cat > /etc/apt/sources.list <<'EOF'
deb http://deb.debian.org/debian bookworm main contrib non-free-firmware
deb http://deb.debian.org/debian bookworm-updates main contrib non-free-firmware
deb http://security.debian.org/debian-security bookworm-security main contrib non-free-firmware
EOF
apt-get update
apt-get install -y --no-install-recommends \
    systemd-sysv systemd-timesyncd udev dbus sudo ca-certificates \
    openssh-server network-manager wpasupplicant wireless-regdb \
    firmware-misc-nonfree usb-modeswitch usb-modeswitch-data \
    kmod usbutils iw iproute2 iputils-ping ethtool rfkill \
    curl less nano tzdata gpiod memtool e2fsprogs dosfstools

echo de1soc > /etc/hostname
cat > /etc/hosts <<'EOF'
127.0.0.1 localhost
127.0.1.1 de1soc
::1 localhost ip6-localhost ip6-loopback
ff02::1 ip6-allnodes
ff02::2 ip6-allrouters
EOF
ln -sfn /usr/share/zoneinfo/Australia/Sydney /etc/localtime
echo Australia/Sydney > /etc/timezone
if ! id de1soc >/dev/null 2>&1; then
    useradd --create-home --shell /bin/bash --groups sudo,dialout de1soc
    passwd -l de1soc
fi
cat > /etc/fstab <<'EOF'
# Boot image uses MBR disk ID 0xde1a2026; p2 contains the root filesystem.
PARTUUID=de1a2026-02 / ext4 defaults,noatime 0 1
LABEL=DE1SOCBOOT /boot vfat defaults,umask=0077 0 2
EOF
mkdir -p /etc/NetworkManager/conf.d /etc/NetworkManager/system-connections
cat > /etc/NetworkManager/conf.d/10-de1soc.conf <<'EOF'
[main]
plugins=keyfile
dhcp=internal
dns=default
rc-manager=symlink
[device]
wifi.scan-rand-mac-address=no
EOF
cat > /etc/NetworkManager/system-connections/wired-dhcp.nmconnection <<'EOF'
[connection]
id=Wired DHCP
uuid=8a727a12-a0c9-4f66-9144-c83e9a1c4198
type=ethernet
autoconnect=true
[ethernet]
[ipv4]
method=auto
[ipv6]
method=auto
EOF
chmod 600 /etc/NetworkManager/system-connections/wired-dhcp.nmconnection
mkdir -p /etc/systemd/timesyncd.conf.d /etc/ssh/sshd_config.d
cat > /etc/systemd/timesyncd.conf.d/10-de1soc.conf <<'EOF'
[Time]
NTP=0.debian.pool.ntp.org 1.debian.pool.ntp.org
FallbackNTP=2.debian.pool.ntp.org 3.debian.pool.ntp.org
EOF
cat > /etc/ssh/sshd_config.d/10-de1soc.conf <<'EOF'
PermitRootLogin no
PermitEmptyPasswords no
PubkeyAuthentication yes
PasswordAuthentication yes
EOF
cat > /etc/systemd/system/de1soc-ssh-hostkeys.service <<'EOF'
[Unit]
Description=Generate this board's SSH host keys
Before=ssh.service
[Service]
Type=oneshot
ExecStart=/usr/bin/ssh-keygen -A
RemainAfterExit=yes
EOF
mkdir -p /etc/systemd/system/ssh.service.d
cat > /etc/systemd/system/ssh.service.d/hostkeys.conf <<'EOF'
[Unit]
Requires=de1soc-ssh-hostkeys.service
After=de1soc-ssh-hostkeys.service
EOF
systemctl enable NetworkManager.service systemd-timesyncd.service ssh.service serial-getty@ttyS0.service
systemctl set-default multi-user.target
if [[ ! -e /var/lib/de1soc-provisioned ]]; then
    # These were generated by this build, not by a deployed board.
    rm -f /etc/ssh/ssh_host_*key /etc/ssh/ssh_host_*key.pub
    : > /etc/machine-id
    rm -f /var/lib/dbus/machine-id
    ln -s /etc/machine-id /var/lib/dbus/machine-id
    passwd -l root
    touch /var/lib/de1soc-provisioned
fi
dpkg --audit
apt-get check
dpkg-query -W -f='${binary:Package}\t${Version}\t${Architecture}\n' > /var/lib/de1soc-package-manifest.tsv
